"""`indexbot render` -- CONTRACTS.md §12/§8. Reads the committed `p/` source
tree via `FilePort` and executes `core/render.py`'s pure `build_render_plan`
against it, writing the resulting dist tree -- `config.json`, the `/p/**`
wire mirror verbatim + its reachable CAS objects, and `/c/index.json`
-- under `--out`. This module no longer writes `/data/catalog/catalog.json`
(`plan_catalog_extraction` WP-11) -- that projection is now emitted by the
`@ocx-sh/catalog` package's own view-model emitter, which reads this
command's `--out` tree directly (CONTRACTS.md §8). `render-deploy.yml`
(ADR-3, WP3-A; build path reshaped by WP-11) runs `site:build` first, then
`indexbot render --out` second, into the same `emptyOutDir`-wiped tree (see
`taskfile.yml`'s `render:build`).

`p/` itself is committed source, never regenerated by this command. Per-
package wrapper Markdown (formerly this module's `--site-dist` output) is
retired: `plan_site_redesign`'s dynamic routes (`site/src/[ns]/[pkg].paths.ts`
globbing `p/*/*.json` at VitePress build time) replace it, so this module
now emits exactly one output tree.

`--check` computes the plan and reports drift against the `--out` tree -- a
planned file missing or content-mismatched, or an existing file under that
tree the plan no longer produces (a stale orphan, e.g. a pruned CAS blob) --
without writing anything. `ExitCode.VALIDATION_FAILURE` on drift,
`ExitCode.OK` when clean; lets CI catch a stale committed dist tree without
re-running the VitePress build (plan risk 3).

`files: FilePort` is a required keyword argument rather than constructed
inside this module (functional core / imperative shell, CONTRACTS.md §0) --
matching `cli/reconcile.py`/`cli/seed_import.py`'s established pattern. This
is this module's own addition on top of CONTRACTS.md §12's literal
`run(args) -> ExitCode` shape; WP2-M's `_DISPATCH` wiring needs to bind the
real `LocalFiles` adapter via a closure/`functools.partial` rather than call
this signature directly as `Callable[[argparse.Namespace], ExitCode]` --
flagged in `open_questions`, same theme as the two sibling modules'.

`--index-dir`/`--out` are relative path *prefixes* within the one `files`
root, not separate filesystem roots -- e.g. `index_dir=""` (`p/` lives at
the checkout root), `out="site/.vitepress/dist"`, both reachable from one
repo-checkout-rooted `LocalFiles` in production. `--out` is `required=True`
at the argparse layer (`cli/main.py`'s `_add_render_arguments`) -- argparse
itself owns the "missing --out" usage error, so this module never raises its
own `ValidationError` for that case.
"""

from __future__ import annotations

import sys
from typing import TYPE_CHECKING, cast

from ocx_indexbot.core.policy import IndexPolicy
from ocx_indexbot.core.render import FileWrite, SourcePackage, build_render_plan
from ocx_indexbot.core.validate_entry import (
    check_digest_self_consistent,
    dangling_references,
    parse_package_root,
)
from ocx_indexbot.errors import AnomalyError, ValidationError
from ocx_indexbot.exit_codes import ExitCode
from ocx_indexbot.model import PackageId

from ._common import write_ci_summary

if TYPE_CHECKING:
    import argparse

    from ocx_indexbot.ports import FilePort


def _p_prefix(index_dir: str) -> str:
    """`index_dir` (a `--index-dir` value, no trailing slash required)
    normalized to the `p/` listing prefix within `files`.

    `.` and `./` mean "the index is the current directory" to every shell on
    earth, and `--index-dir .` is what a hand-written pipeline types. A
    `FilePort` key never carries that prefix, so the un-normalized `./p/`
    matched nothing and rendered a complete, valid, **empty** index — exit 0,
    `{"packages":{}}`, deployed over a populated one. Measured live.
    """
    stripped = index_dir.strip().rstrip("/")
    if stripped in {"", "."}:
        return "p/"
    return f"{stripped.removeprefix('./')}/p/"


def _package_dir(index_dir: str, package_id: PackageId) -> str:
    return f"{_p_prefix(index_dir)}{package_id}"


def _output_prefix(output_root: str) -> str:
    """`output_root` (a `--out` value) normalized to a path prefix -- `""`
    (the `files` root itself) or `"<root>/"`."""
    stripped = output_root.rstrip("/")
    return f"{stripped}/" if stripped else ""


def _read_required_bytes(files: FilePort, path: str) -> bytes:
    """`files.read_bytes(path)`, raising `ValidationError` if it vanished
    between being listed (`FilePort.list_files`) and read -- a torn local
    checkout; the closest existing error class for "an input this call
    expected isn't there"."""
    content = files.read_bytes(path)
    if content is None:
        raise ValidationError(f"expected file vanished during render: {path!r}")
    return content


def _package_roots(
    files: FilePort, index_dir: str, *, name_segments: int
) -> list[tuple[PackageId, str]]:
    """`(PackageId, root_path)` for every `p/<namespace>/<package>.json` --
    exactly `name_segments` path segments under the `p/` prefix ending in
    `.json`, which
    excludes every CAS subtree file (`p/<ns>/<pkg>/o/sha256/**`, always
    3+ segments). Mirrors `cli/reconcile.py`'s `_discover_package_ids`
    predicate verbatim -- see `open_questions` re: extracting a shared
    helper, out of this work package's scope to do unilaterally."""
    prefix = _p_prefix(index_dir)
    roots: list[tuple[PackageId, str]] = []
    for path in files.list_files(prefix):
        segments = path.removeprefix(prefix).split("/")
        # A root document sits at exactly the declared depth; anything deeper
        # is that package's own CAS subtree, not a root of its own.
        if len(segments) == name_segments and segments[-1].endswith(".json"):
            segments[-1] = segments[-1].removesuffix(".json")
            roots.append((PackageId(segments=tuple(segments)), path))
    return roots


def _quarantine(package_id: PackageId, reason: str, *, why: str, detail: str, strict: bool) -> None:
    """Announce `package_id` as left out of the rendered tree, or raise
    `AnomalyError` under `--strict`."""
    message = f"render: quarantined {package_id}: {reason}"
    if strict:
        raise AnomalyError(message)
    print(message, file=sys.stderr)
    write_ci_summary(
        "indexbot render: package quarantined",
        f"`{package_id}` is left out of the rendered tree: {why}.",
        detail=detail,
    )


def _load_source_package(
    files: FilePort, index_dir: str, package_id: PackageId, root_path: str, *, strict: bool
) -> SourcePackage | None:
    """The package as committed, or `None` when it must not be served.

    A blob whose bytes do not hash to the digest its filename claims is
    corruption and always `AnomalyError` -- `--strict` or not. A root that
    cannot be parsed, or that points at a CAS object absent from the tree, is
    quarantined whole (`None`, announced on stderr and the CI summary): the
    root's bytes are served verbatim or not at all, so dropping one row would
    mean re-serializing it. `--strict` turns the quarantine into `AnomalyError`.
    """
    root_raw = _read_required_bytes(files, root_path)
    try:
        root = parse_package_root(root_raw)
    except ValidationError as error:
        reason = f"malformed root {root_path}: {error}"
        _quarantine(
            package_id,
            reason,
            why=f"its root `{root_path}` is malformed",
            detail=str(error),
            strict=strict,
        )
        return None
    cas_prefix = f"{_package_dir(index_dir, package_id)}/o/sha256/"
    content_by_digest: dict[str, bytes] = {}
    present: set[str] = set()
    for cas_path in files.list_files(cas_prefix):
        name = cas_path.removeprefix(cas_prefix)
        content = _read_required_bytes(files, cas_path)
        digest = f"sha256:{name.split('.', 1)[0]}"
        check_digest_self_consistent(digest, content)
        present.add(digest)
        content_by_digest[f"sha256:{name}"] = content

    dangling = dangling_references(root, frozenset(present))
    if dangling:
        _quarantine(
            package_id,
            f"dangling {', '.join(dangling)}",
            why="its root points at CAS objects that are not in the source tree",
            detail="\n".join(dangling),
            strict=strict,
        )
        return None
    return SourcePackage(
        package_id=package_id, root=root, root_raw=root_raw, content_by_digest=content_by_digest
    )


def _load_source_packages(
    files: FilePort, index_dir: str, *, name_segments: int, strict: bool
) -> list[SourcePackage]:
    loaded = (
        _load_source_package(files, index_dir, package_id, root_path, strict=strict)
        for package_id, root_path in _package_roots(files, index_dir, name_segments=name_segments)
    )
    return [source for source in loaded if source is not None]


def _write_tree(files: FilePort, output_root: str, file_writes: tuple[FileWrite, ...]) -> None:
    prefix = _output_prefix(output_root)
    for file_write in file_writes:
        path = f"{prefix}{file_write.path}"
        if isinstance(file_write.content, str):
            files.write_text(path, file_write.content)
        else:
            files.write_bytes(path, file_write.content)


def _tree_drifted(files: FilePort, output_root: str, file_writes: tuple[FileWrite, ...]) -> bool:
    prefix = _output_prefix(output_root)
    planned = {f"{prefix}{file_write.path}": file_write for file_write in file_writes}
    if set(files.list_files(output_root.rstrip("/"))) != set(planned):
        return True
    for path, file_write in planned.items():
        content = file_write.content
        expected = content.encode("utf-8") if isinstance(content, str) else content
        if files.read_bytes(path) != expected:
            return True
    return False


def run(args: argparse.Namespace, *, files: FilePort, policy: IndexPolicy) -> ExitCode:
    """`indexbot render` entry point. Expected `args` attributes:
    `index_dir` (str, required), `out` (str, required), `check` (bool),
    `allow_empty` (bool), `strict` (bool) --
    argparse's default dest derivation already maps `--index-dir`/`--out`/
    `--check` to those names, so WP2-M's `subparsers.add_parser` wiring
    needs no extra `dest=` overrides.
    """
    index_dir = cast(str, args.index_dir)
    out = cast(str, args.out)
    check = bool(getattr(args, "check", False))

    if not _package_roots(files, index_dir, name_segments=policy.name_segments) and not bool(
        getattr(args, "allow_empty", False)
    ):
        raise ValidationError(
            f"render found no package roots under {_p_prefix(index_dir)!r} — "
            "a typo in --index-dir renders a valid but EMPTY index, which then "
            "deploys over a populated one. Pass --allow-empty if that is really "
            "what you mean (a brand-new index before its first announce)."
        )
    sources = _load_source_packages(
        files,
        index_dir,
        name_segments=policy.name_segments,
        strict=bool(getattr(args, "strict", False)),
    )
    if not sources and not bool(getattr(args, "allow_empty", False)):
        raise ValidationError(
            f"every package root under {_p_prefix(index_dir)!r} was quarantined — "
            "rendering would publish an EMPTY index over a populated one. Fix the "
            "quarantined packages, or pass --allow-empty if that is really what you mean."
        )
    plan = build_render_plan(sources, name_segments=policy.name_segments)

    if check:
        return ExitCode.VALIDATION_FAILURE if _tree_drifted(files, out, plan) else ExitCode.OK

    _write_tree(files, out, plan)
    return ExitCode.OK
